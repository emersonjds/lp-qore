import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCE_URL =
  "https://servicodados.ibge.gov.br/api/v3/malhas/paises/BR?formato=image/svg+xml&intrarregiao=UF&qualidade=minima";
const outputFile = fileURLToPath(new URL("../src/config/brazil-map.ts", import.meta.url));
const SOURCE_UNITS_PER_DEGREE = 10_000;
const MAP_UNITS_PER_DEGREE = 20;

const response = await fetch(SOURCE_URL);
if (!response.ok) throw new Error(`IBGE answered ${response.status}`);
const svg = await response.text();

const [viewBoxLongitude, viewBoxLatitude, viewBoxWidth, viewBoxHeight] = svg
  .match(/viewBox="([^"]+)"/)[1]
  .split(/\s+/)
  .map(Number);
const originLongitude = viewBoxLongitude;
const originLatitude = -viewBoxLatitude;

const toMapUnits = (sourceX, sourceY) => [
  Math.round((sourceX / SOURCE_UNITS_PER_DEGREE - originLongitude) * MAP_UNITS_PER_DEGREE),
  Math.round((originLatitude - sourceY / SOURCE_UNITS_PER_DEGREE) * MAP_UNITS_PER_DEGREE),
];

const simplifyPath = (sourcePath) => {
  const rings = [];
  let x = 0;
  let y = 0;
  for (const [, command, rawValues] of sourcePath.matchAll(/([MlhZ])([^MlhZ]*)/g)) {
    const values = rawValues.split(/[\s,]+/).filter(Boolean).map(Number);
    if (command === "M") {
      [x, y] = values;
      rings.push([toMapUnits(x, y)]);
    }
    if (command === "h") {
      x += values.reduce((sum, value) => sum + value, 0);
      rings.at(-1).push(toMapUnits(x, y));
    }
    if (command === "l") {
      for (let index = 0; index < values.length; index += 2) {
        x += values[index];
        y += values[index + 1];
        rings.at(-1).push(toMapUnits(x, y));
      }
    }
  }

  return rings
    .map((ring) => {
      const [[startX, startY]] = ring;
      const deltas = [];
      let [previousX, previousY] = [startX, startY];
      for (const [pointX, pointY] of ring.slice(1)) {
        if (pointX === previousX && pointY === previousY) continue;
        deltas.push(`${pointX - previousX} ${pointY - previousY}`);
        [previousX, previousY] = [pointX, pointY];
      }
      return deltas.length < 2 ? "" : `M${startX} ${startY}l${deltas.join(" ")}Z`;
    })
    .join("");
};

const states = Object.fromEntries(
  [...svg.matchAll(/<path id="(\d+)" d="([^"]+)"/g)].map(([, code, path]) => [code, simplifyPath(path)]),
);

const width = Math.ceil(viewBoxWidth * MAP_UNITS_PER_DEGREE);
const height = Math.ceil(viewBoxHeight * MAP_UNITS_PER_DEGREE);

const source = `// Generated by scripts/generate-brazil-map.mjs from the IBGE malhas API. Do not edit by hand.
export const BRAZIL_MAP = {
  viewBox: "0 0 ${width} ${height}",
  origin: { longitude: ${originLongitude}, latitude: ${originLatitude} },
  unitsPerDegree: ${MAP_UNITS_PER_DEGREE},
  states: ${JSON.stringify(states, null, 4).replace(/\n}$/, "\n  }")},
} as const;
`;

await writeFile(outputFile, source);
console.log(`wrote ${Object.keys(states).length} states to ${outputFile}`);
